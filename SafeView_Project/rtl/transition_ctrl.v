// ============================================================================
// Module:  transition_ctrl
// File:    rtl/transition_ctrl.v
// Standard: Verilog-2001, synthesizable
// ============================================================================
//
// === Module Purpose ===
// Transition effect engine for image-carousel display (Plan 1: fixed-region).
// Responsibilities:
//   1. Fixed-region addressing: figure each image's physical SDRAM region from
//      its 2-bit image index. Four images live permanently in four fixed
//      regions (REGION_0..REGION_3), all pre-loaded at power-up, so navigation
//      is a pure pointer change with zero SD read latency at run time.
//   2. Per-frame transition coefficient generation: alpha (fade) and
//      off (slide displacement).
//   3. Transition mode selection and tear-free output latching at frame
//      boundaries (vs falling edge).
//
// This module does NOT perform pixel blending (done by transition_mixer +
// alpha_mixer) and does NOT access any ROM or SDRAM.
//
// === Fixed-Region Model (no more 3-region rotation) ===
// SDRAM is 2M x 32bit (8 MB). Each 640x480 image occupies 307200 words, so
// four images fit in four fixed regions:
//   REGION 0 : image 0 @ 21'd0
//   REGION 1 : image 1 @ 21'd307200
//   REGION 2 : image 2 @ 21'd614400
//   REGION 3 : image 3 @ 21'd921600
// Every image is written ONCE at startup (by sd_card_bmp) and never
// overwritten afterwards. Reading for a transition is therefore always
// REGION(old_img_idx) vs REGION(new_img_idx) -- no write/read region
// aliasing is possible, so the old three-region rotation invariant and its
// O_wr_addr output are no longer needed.
//
// === Commit Detection (CDC) ===
// I_commit_toggle is a single-bit toggle generated by sd_card_bmp in the
// sd_card_clk domain; it flips exactly once per image commit (first image
// and every subsequent navigation). A 3-stage shift synchronizer + edge
// detect produces commit_pulse.
//
// I_img_idx (3-bit) is the new display image index. It is held stable by
// sd_card_bmp from one commit until the next (i.e. for the whole time the
// image is displayed, far longer than the 2-stage synchronizer latency), so
// it can be safely sampled when commit_pulse fires.
//
// === Transition Start / Settle ===
// On the first commit there is no transition: the module simply latches the
// first image and drives a single stream (dual_en=0).
// On each subsequent commit a transition is started from the currently
// displayed image (cur_idx) to the new one (I_img_idx):
//   O_rd_addr_a <- REGION(cur_idx)   (old image)
//   O_rd_addr_b <- REGION(new_idx)   (new image)
//   cur_idx     <- new_idx
// The fade/slide coefficients progress one step per frame (vs falling edge).
// At the end of a fade, dual_en is held at 1 / alpha=255 for one settle
// frame while O_rd_addr_a is moved onto the new image region; this lets the
// read engine refill stream A with the new image before dual_en is dropped,
// preventing a one-frame flash-back to the old image.
//
// === Rapid Manual Switching ===
// A commit arriving mid-transition sets pending_commit / pending_idx; the
// running transition completes uninterrupted, then a new transition is
// auto-started at the next frame boundary. Because all images are preloaded,
// this only needs to remember the latest target index -- there is no write
// region to protect anymore.
//
// === No-Tearing Guarantee ===
// All outputs that affect which regions are read (O_rd_addr_a/b, O_dual_en,
// O_alpha, O_off, O_mode) change only at frame boundaries (vs falling edge).
// The first transition start from S_IDLE is the sole exception: it updates
// immediately on the commit cycle, which is safe because the read engine
// only samples configuration at frame start.
// ============================================================================

module transition_ctrl #(
    parameter ADDR_BITS     = 21,
    parameter REGION_0_ADDR = 21'd0,
    parameter REGION_1_ADDR = 21'd307200,
    parameter REGION_2_ADDR = 21'd614400,
    parameter REGION_3_ADDR = 21'd921600,
    parameter REGION_4_ADDR = 21'd1228800,
    parameter REGION_5_ADDR = 21'd1536000,
    parameter N_FRAMES      = 32,
    parameter H_ACTIVE      = 640
)(
    input  wire                    I_pix_clk,
    input  wire                    I_rst,
    input  wire                    I_vs,
    input  wire                    I_commit_toggle, // toggles on each image commit (sd_card_clk domain)
    input  wire [2:0]              I_img_idx,       // new display image index, held stable per image
    input  wire [1:0]              I_fx_sel,        // 特效选择：0=淡入淡出(fade), 1=滑动(slide-right)
    input  wire                    I_force_quake,   // 1=地震告警中，强制短暂显示告警图 (REGION_5)
    output reg                     O_dual_en,
    output reg  [7:0]              O_alpha,
    output reg  [1:0]              O_mode,
    output reg  [10:0]             O_off,
    output reg                     O_transition_busy,
    output reg  [ADDR_BITS-1:0]    O_rd_addr_a,
    output reg  [ADDR_BITS-1:0]    O_rd_addr_b,
    output reg                     O_cfg_toggle
);

    // ========================================================================
    // Constants
    // ========================================================================
    localparam integer ALPHA_STEP       = 256 / N_FRAMES;
    localparam [7:0]   ALPHA_STEP_8BIT  = ALPHA_STEP[7:0];
    localparam [10:0]  OFF_STEP = H_ACTIVE[10:0] / N_FRAMES[10:0];
    localparam [10:0]  H_ACTIVE_11 = H_ACTIVE[10:0];

    localparam [1:0] S_IDLE   = 2'd0;
    localparam [1:0] S_RUN    = 2'd1;
    localparam [1:0] S_SETTLE = 2'd2;

    // ========================================================================
    // Control Registers
    // ========================================================================
    reg [2:0]  cur_idx;           // currently displayed image index
    reg        first_commit_done;
    reg        pending_commit;
    reg [2:0]  pending_idx;
    reg [1:0]  state;

    // 特效选择输入的 CDC 同步（静态电平，2 级同步器足够）
    reg [1:0]  I_fx_sel_d1;
    reg [1:0]  I_fx_sel_d2;

    // ========================================================================
    // Frame Tick Detection (vs falling edge = frame start)
    // ========================================================================
    reg vs_d;
    reg force_q_d;
    wire frame_tick = vs_d & ~I_vs;

    // ========================================================================
    // CDC: commit toggle (3 级) + img_idx (2 级，长保持数据)
    // ========================================================================
    reg        commit_d1, commit_d2, commit_d3;
    reg [2:0]  img_d1, img_d2;

    wire commit_pulse = commit_d2 ^ commit_d3;

    // ========================================================================
    // Image Index -> Physical Base Address (combinational function)
    // ========================================================================
    function [ADDR_BITS-1:0] REGION;
        input [2:0] i;
        begin
            case (i)
                3'd0:    REGION = REGION_0_ADDR;
                3'd1:    REGION = REGION_1_ADDR;
                3'd2:    REGION = REGION_2_ADDR;
                3'd3:    REGION = REGION_3_ADDR;
                3'd4:    REGION = REGION_4_ADDR;
                3'd5:    REGION = REGION_5_ADDR;
                default: REGION = REGION_0_ADDR;
            endcase
        end
    endfunction

    // ========================================================================
    // Main Sequential Logic
    // ========================================================================
    always @(posedge I_pix_clk) begin
        if (I_rst) begin
            cur_idx           <= 3'd0;
            first_commit_done <= 1'b0;
            pending_commit    <= 1'b0;
            pending_idx       <= 3'd0;
            state             <= S_IDLE;
            I_fx_sel_d1       <= 2'd0;
            I_fx_sel_d2       <= 2'd0;
            vs_d              <= 1'b0;
            commit_d1         <= 1'b0;
            commit_d2         <= 1'b0;
            commit_d3         <= 1'b0;
            img_d1            <= 3'd0;
            img_d2            <= 3'd0;
            force_q_d         <= 1'b0;

            O_dual_en         <= 1'b0;
            O_alpha           <= 8'd0;
            O_mode            <= 2'd0;
            O_off             <= 11'd0;
            O_transition_busy <= 1'b0;
            O_rd_addr_a       <= REGION_0_ADDR;
            O_rd_addr_b       <= REGION_0_ADDR;
            O_cfg_toggle      <= 1'b0;
        end else begin
            vs_d        <= I_vs;
            I_fx_sel_d1 <= I_fx_sel;
            I_fx_sel_d2 <= I_fx_sel_d1;
            force_q_d   <= I_force_quake;

            commit_d1 <= I_commit_toggle;
            commit_d2 <= commit_d1;
            commit_d3 <= commit_d2;

            img_d1 <= I_img_idx;
            img_d2 <= img_d1;

            if (I_force_quake && !force_q_d) begin
                // === 地震告警触发：瞬间切到告警图 (REGION_5)，单流无转场 ===
                state             <= S_IDLE;
                pending_commit    <= 1'b0;
                O_dual_en         <= 1'b0;
                O_alpha           <= 8'd0;
                O_mode            <= 2'd0;
                O_off             <= 11'd0;
                O_transition_busy <= 1'b0;
                O_rd_addr_a       <= REGION_5_ADDR;
                O_rd_addr_b       <= REGION_5_ADDR;
                O_cfg_toggle      <= ~O_cfg_toggle;
            end else if (!I_force_quake && force_q_d) begin
                // === 告警解除：恢复告警前显示图，单流无转场 ===
                state             <= S_IDLE;
                pending_commit    <= 1'b0;
                O_dual_en         <= 1'b0;
                O_alpha           <= 8'd0;
                O_mode            <= 2'd0;
                O_off             <= 11'd0;
                O_transition_busy <= 1'b0;
                O_rd_addr_a       <= REGION(cur_idx);
                O_rd_addr_b       <= REGION(cur_idx);
                O_cfg_toggle      <= ~O_cfg_toggle;
            end else if (!I_force_quake) begin
            case (state)
                // --------------------------------------------------------
                // S_IDLE: waiting for a commit
                // --------------------------------------------------------
                S_IDLE: begin
                    if (commit_pulse) begin
                        if (!first_commit_done) begin
                            // === First image: single stream, no transition ===
                            cur_idx           <= img_d2;
                            O_rd_addr_a       <= REGION(img_d2);
                            O_rd_addr_b       <= REGION(img_d2);
                            O_dual_en         <= 1'b0;
                            O_mode            <= 2'd0;
                            O_alpha           <= 8'd0;
                            O_off             <= 11'd0;
                            O_transition_busy <= 1'b0;
                            O_cfg_toggle      <= ~O_cfg_toggle;
                            first_commit_done <= 1'b1;
                        end else begin
                            // === Subsequent commit: start transition ===
                            O_rd_addr_a       <= REGION(cur_idx);
                            O_rd_addr_b       <= REGION(img_d2);
                            cur_idx           <= img_d2;

                            O_dual_en         <= 1'b1;
                            O_alpha           <= 8'd0;
                            O_off             <= 11'd0;
                            O_mode            <= (I_fx_sel_d2 == 2'd1) ? 2'd2 : 2'd1;
                            O_transition_busy <= 1'b1;
                            O_cfg_toggle      <= ~O_cfg_toggle;

                            state <= S_RUN;
                        end
                    end
                end

                // --------------------------------------------------------
                // S_RUN: transition in progress
                // --------------------------------------------------------
                S_RUN: begin
                    // Mid-transition commit: remember latest target, do not
                    // disturb the running transition's A/B addresses.
                    if (commit_pulse) begin
                        pending_commit <= 1'b1;
                        pending_idx    <= img_d2;
                    end

                    if (frame_tick) begin
                        if ({1'b0, O_alpha} + {1'b0, ALPHA_STEP_8BIT} > 9'd255)
                            O_alpha <= 8'hFF;
                        else
                            O_alpha <= O_alpha + ALPHA_STEP_8BIT;

                        if (O_off + OFF_STEP > H_ACTIVE_11)
                            O_off <= H_ACTIVE_11;
                        else
                            O_off <= O_off + OFF_STEP;

                        if (({1'b0, O_alpha} + {1'b0, ALPHA_STEP_8BIT} > 9'd255) ||
                            (O_off + OFF_STEP > H_ACTIVE_11)) begin
                            // Hold dual_en=1 / alpha=255 one more frame and
                            // move stream A onto the new image region so the
                            // read engine refills A before we drop dual_en.
                            O_dual_en    <= 1'b1;
                            O_alpha      <= 8'hFF;
                            O_off        <= 11'd0;
                            O_mode       <= 2'd1;
                            O_rd_addr_a  <= REGION(cur_idx);
                            O_cfg_toggle <= ~O_cfg_toggle;
                            state        <= S_SETTLE;
                        end
                    end
                end

                // --------------------------------------------------------
                // S_SETTLE: extra frame of alpha=255 for the A refill, then
                //           drop dual_en and pass stream A through directly.
                // --------------------------------------------------------
                S_SETTLE: begin
                    if (commit_pulse) begin
                        pending_commit <= 1'b1;
                        pending_idx    <= img_d2;
                    end
                    if (frame_tick) begin
                        O_dual_en         <= 1'b0;
                        O_alpha           <= 8'd0;
                        O_mode            <= 2'd0;
                        O_off             <= 11'd0;
                        O_transition_busy <= 1'b0;
                        O_cfg_toggle      <= ~O_cfg_toggle;
                        state             <= S_IDLE;
                    end
                end

                default: begin
                    state <= S_IDLE;
                end
            endcase

            // ============================================================
            // Pending commit auto-start (S_IDLE, frame_tick)
            // ============================================================
            if ((state == S_IDLE) && first_commit_done &&
                pending_commit && frame_tick) begin
                pending_commit <= 1'b0;

                O_rd_addr_a       <= REGION(cur_idx);
                O_rd_addr_b       <= REGION(pending_idx);
                cur_idx           <= pending_idx;

                O_dual_en         <= 1'b1;
                O_alpha           <= 8'd0;
                O_off             <= 11'd0;
                O_mode            <= (I_fx_sel_d2 == 2'd1) ? 2'd2 : 2'd1;
                O_transition_busy <= 1'b1;
                O_cfg_toggle      <= ~O_cfg_toggle;

                state <= S_RUN;
            end
            end
        end
    end

endmodule